// Writes src/icons/components/rootIcons.ts: the icons that `@jahia/moonstone` still exports, deprecated one by one
import { readdirSync, writeFileSync } from 'node:fs';

const dir = 'src/icons/components';
const names = readdirSync(dir)
    .filter(file => file.endsWith('.tsx'))
    .map(file => file.slice(0, -'.tsx'.length))
    .sort();

const exports = names.map(name => [
    `/** @deprecated Import \`${name}\` from \`@jahia/moonstone/icons\` */`,
    `export const ${name}: typeof icons.${name} = /* @__PURE__ */ deprecatedIcon(icons.${name});`,
].join('\n'));

writeFileSync(`${dir}/rootIcons.ts`, [
    '// Generated by scripts/build-root-icons.mjs',
    'import { deprecatedIcon } from \'../deprecatedIcon\';',
    'import * as icons from \'./index\';',
    '',
    ...exports,
    '',
].join('\n'));
